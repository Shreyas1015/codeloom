import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";
import { dataError } from "../errors.js";
import { readJson } from "./json.js";
import { CODELOOM_DIR, WORKSPACE_FILE } from "./paths.js";

// v0.3 spec §1. The indexer step that WRITES spec-candidates.json is v0.3 Task 1 (built in parallel); this
// file holds what the readers (v0.3 Task 2: MCP tools, doctor) need. When Task 1 lands, its
// SpecCandidatesFileSchema / specs config schema in store/schemas.ts replace the ones here (same shape).

/** `<ws>/.codeloom/spec-candidates.json`: generated by `codeloom index`, committed, deterministic. */
export const SPEC_CANDIDATES_FILE = "spec-candidates.json";

/** Where a doc mentions the journey: a route, page path, table, queue or stop symbol, as a whole token. */
export const DocEvidenceSchema = z.object({
  kind: z.enum(["route", "page", "table", "queue", "symbol"]),
  term: z.string(),
  /** The doc's repo-relative path. */
  file: z.string(),
  line: z.number().int().positive(),
});
export type DocEvidence = z.infer<typeof DocEvidenceSchema>;

/** A commit that names the ticket and touches a file under the journey's stops. */
export const TicketEvidenceSchema = z.object({
  /** Short hash. */
  commit: z.string(),
  /** The journey file the commit touched (repo-relative). */
  file: z.string(),
  /** Commit subject, ≤ 120 characters. */
  subject: z.string(),
});
export type TicketEvidence = z.infer<typeof TicketEvidenceSchema>;

/** One candidate: `ref` is `repo:path` for a doc, the key for a ticket. `evidence` holds the first 5 hits,
 * `count` all of them; `score` orders candidates (docs: weighted hits; tickets: distinct commits). */
export const DocCandidateSchema = z.object({
  ref: z.string(),
  score: z.number(),
  count: z.number().int().nonnegative(),
  evidence: z.array(DocEvidenceSchema),
});
export type DocCandidate = z.infer<typeof DocCandidateSchema>;

export const TicketCandidateSchema = z.object({
  ref: z.string(),
  score: z.number(),
  count: z.number().int().nonnegative(),
  evidence: z.array(TicketEvidenceSchema),
});
export type TicketCandidate = z.infer<typeof TicketCandidateSchema>;

/** Per journey: ≤ 20 docs and ≤ 20 tickets, sorted by score desc then ref. */
export const JourneySpecCandidatesSchema = z.object({
  docs: z.array(DocCandidateSchema),
  tickets: z.array(TicketCandidateSchema),
});
export type JourneySpecCandidates = z.infer<typeof JourneySpecCandidatesSchema>;

export const SpecCandidatesFileSchema = z.object({
  version: z.literal(1),
  journeys: z.record(z.string(), JourneySpecCandidatesSchema),
});
export type SpecCandidatesFile = z.infer<typeof SpecCandidatesFileSchema>;

/** The workspace file's optional `specs` block (spec §1). */
export const SpecsConfigSchema = z.object({
  docs: z.array(z.string()).optional(),
  ignoreDocs: z.array(z.string()).optional(),
  ticketPattern: z.string().optional(),
  ignorePrefixes: z.array(z.string()).optional(),
});
export type SpecsConfig = z.infer<typeof SpecsConfigSchema>;

export const DEFAULT_TICKET_PATTERN = "\\b[A-Z][A-Z0-9]+-\\d+\\b";
export const DEFAULT_IGNORE_PREFIXES: readonly string[] = ["CVE", "UTF", "ISO", "RFC", "SHA"];

/** What ticket keys must look like: the pattern (compiled) and the prefixes that are never tickets. */
export interface TicketRules { ticketPattern: string; ignorePrefixes: readonly string[] }

/** Missing → null. Bad JSON or shape → CodeloomError (exit 2; delete it and re-index). */
export function readSpecCandidates(root: string): SpecCandidatesFile | null {
  return readJson(join(root, CODELOOM_DIR, SPEC_CANDIDATES_FILE), SpecCandidatesFileSchema);
}

/** Compile a ticket pattern; a bad regex is a data error naming the setting. */
export function compileTicketPattern(pattern: string): RegExp {
  try {
    return new RegExp(pattern);
  } catch (err) {
    throw dataError(`specs.ticketPattern in ${WORKSPACE_FILE} is not a valid regular expression (${err instanceof Error ? err.message : String(err)}). Fix it by hand.`);
  }
}

/** The ticket rules from the workspace file's `specs` block, with defaults. No workspace file (a single repo
 * without init) → defaults. A bad `specs` block or regex → CodeloomError (exit 2). */
export function readSpecsConfig(root: string): TicketRules {
  const path = join(root, WORKSPACE_FILE);
  let specs: SpecsConfig = {};
  if (existsSync(path)) {
    let raw: unknown;
    try {
      raw = JSON.parse(readFileSync(path, "utf8"));
    } catch {
      raw = {}; // loadWorkspace reports a broken workspace file
    }
    const block = (raw as { specs?: unknown } | null)?.specs;
    if (block !== undefined) {
      const parsed = SpecsConfigSchema.safeParse(block);
      if (!parsed.success) {
        const lines = parsed.error.issues.map((i) => `  - specs.${i.path.join(".")}: ${i.message}`);
        throw dataError(`${path} has an unexpected "specs" block:\n${lines.join("\n")}\nFix it by hand.`);
      }
      specs = parsed.data;
    }
  }
  const ticketPattern = specs.ticketPattern ?? DEFAULT_TICKET_PATTERN;
  compileTicketPattern(ticketPattern);
  return { ticketPattern, ignorePrefixes: specs.ignorePrefixes ?? DEFAULT_IGNORE_PREFIXES };
}
